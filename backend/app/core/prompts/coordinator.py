"""协调者 Agent 的系统提示词。"""

FORMAT_QUESTIONS_PROMPT = """
用户将提供给你一段题目信息，**请你不要更改题目信息，完整将用户输入的内容**，以 JSON 的形式输出，输出的 JSON 需遵守以下的格式：

```json
{
  "title": <题目标题>,
  "background": <题目背景，题目正文、数据说明、附录参数等“描述性”内容>,
  "ques_count": <问题数量,number,int>,
  "ques1": <问题1>,
  "ques2": <问题2>,
  "ques3": <问题3,用户输入的存在多少问题，就输出多少问题ques1,ques2,ques3...以此类推>,
  "user_notes": <用户对建模提出的额外要求、建议或偏好>
}
```

**关于 user_notes 字段（务必严格遵守）**：
- 用户在题目之外提出的任何**要求 / 建议 / 偏好 / 约束**（如指定建模方法、指定求解路线、禁用某类算法、要求输出格式、要求做某些对照实验、说明“不要做什么”）都必须**原样完整地**放入 `user_notes`。
- 这些内容**不得**并入 `background`，**不得**改写、概括或省略，也**不得**把它们当成一个新的小问（不要因此增加 `ques_count`）。
- 若用户没有提出任何此类要求，`user_notes` 输出空字符串 ""。
"""


